#!/usr/bin/env python3
"""
A stand-in for Snapmaker Orca's command line, for checks that must not need the real engine.

It answers the way the engine's command line does (`--help` with "<App>-<version>:" first, `--export-settings`, `--slice <plate>
--load-settings <machine;process> --load-filaments <list> --outputdir <folder> <model>`) and writes `plate_1.gcode` and `result.json`. The
G-code is not a slice of the model: it is a small two-head tower with perimeters, infill, a top surface and a prime tower, written the way
the engine writes it (`;TYPE:`, `;LAYER_CHANGE`, `;Z:`, `;HEIGHT:`, `;WIDTH:`, M83, header estimates), so the Preview, the checks and the
queue can be driven end to end. It says so in the file.

    python3 tools/stand-in-engine.py --make-engine <folder>     writes <folder>/bin/snapmaker-orca and <folder>/resources/profiles/Snapmaker
                                                                (a machine, three process presets and a material, shaped like Snapmaker's own)

Environment: STAND_IN_FAIL=1 makes a slice fail like a missing model; STAND_IN_HEADS=1 writes a single-head file; STAND_IN_DELAY=<seconds>
waits before writing (to see progress and Cancel); STAND_IN_ARGS=<file> records the command line it was given.
"""
import json
import math
import os
import stat
import sys
import time

VERSION = "02.04.01.00"
APP = "Snapmaker_Orca"


def square(cx, cy, half):
    return [(cx - half, cy - half), (cx + half, cy - half), (cx + half, cy + half), (cx - half, cy + half)]


def gcode(heads, layers=60, height=0.2):
    out = ["; stand-in G-code from tools/stand-in-engine.py: a tower, not a slice of your model",
           "; HEADER_BLOCK_START", "; generated by " + APP + " " + VERSION + " (stand-in)",
           f"; total layer number = {layers}", "; filament used [mm] = " + ", ".join(f"{1500 + i * 220:.2f}" for i in range(heads)),
           "; filament used [g] = " + ", ".join(f"{3.5 + i * 0.7:.2f}" for i in range(heads)), f"; total filament used [g] = {sum(3.5 + i * 0.7 for i in range(heads)):.2f}",
           "; estimated printing time (normal mode) = 14m 20s", "; HEADER_BLOCK_END", "M83", "G90", "G28", "T0"]
    e = 0.0
    tool = 0

    def line(x0, y0, x1, y1, feat, width, speed):
        nonlocal e
        length = math.hypot(x1 - x0, y1 - y0)
        out.append(f"G1 X{x1:.3f} Y{y1:.3f} E{length * width * height / 2.405:.5f} F{speed * 60:.0f}")

    def polygon(pts, feat, width, speed):
        out.append(f";TYPE:{feat}")
        out.append(f";WIDTH:{width}")
        out.append(f"G1 X{pts[0][0]:.3f} Y{pts[0][1]:.3f} F9000")
        for a, b in zip(pts, pts[1:] + pts[:1]):
            line(a[0], a[1], b[0], b[1], feat, width, speed)

    for layer in range(layers):
        z = round(height * (layer + 1), 3)
        want = 0 if layer < layers // 2 or heads == 1 else 1
        out += [";LAYER_CHANGE", f";Z:{z}", f";HEIGHT:{height}", f"G1 Z{z:.3f} F600"]
        if want != tool:
            out += [";TYPE:Custom", f"T{want}"]
            tool = want
        out.append(f"G1 X135 Y135 F9000")
        polygon(square(135.5, 136, 15), "Outer wall", 0.42, 60)
        polygon(square(135.5, 136, 14.55), "Inner wall", 0.45, 100)
        top = layer >= layers - 4
        out.append(";TYPE:Top surface" if top else ";TYPE:Sparse infill")
        out.append(";WIDTH:0.45")
        step = 1.0 if top else 4.0
        y = 136 - 13.5
        flip = False
        while y < 136 + 13.5:
            a, b = (122, 149) if not flip else (149, 122)
            out.append(f"G1 X{a:.2f} Y{y:.2f} F9000")
            line(a, y, b, y, "infill", 0.45, 120 if not top else 60)
            y += step
            flip = not flip
        if heads > 1:
            polygon(square(30, 235, 14), "Prime tower", 0.5, 90)
            polygon(square(30, 235, 12), "Prime tower", 0.5, 90)
    out += ["M104 S0", "M140 S0", "G28 X Y", "; end of the stand-in file"]
    return "\n".join(out) + "\n"


def make_engine(folder):
    bin_dir = os.path.join(folder, "bin")
    os.makedirs(bin_dir, exist_ok=True)
    program = os.path.join(bin_dir, "snapmaker-orca")
    with open(program, "w") as fh:
        fh.write("#!" + sys.executable + "\nimport runpy, sys\nsys.argv[0] = " + repr(os.path.abspath(__file__)) + "\nrunpy.run_path(" + repr(os.path.abspath(__file__)) + ", run_name='__main__')\n")
    os.chmod(program, os.stat(program).st_mode | stat.S_IEXEC)
    presets = os.path.join(folder, "resources", "profiles", "Snapmaker")
    os.makedirs(presets, exist_ok=True)

    def write(name, data):
        with open(os.path.join(presets, name + ".json"), "w") as fh:
            json.dump(data, fh)

    write("base", {"type": "machine", "name": "base", "from": "system", "instantiation": "false", "printer_model": "Snapmaker U1"})
    write("printer", {"type": "machine", "name": "Snapmaker U1 (0.4 nozzle)", "inherits": "base", "instantiation": "true", "nozzle_diameter": ["0.4"] * 4})
    for name, height, wall, infill, speed in (("0.12mm Fine", "0.12", "3", "15%", "150"), ("0.20mm Standard", "0.2", "3", "15%", "200"), ("0.28mm Draft", "0.28", "2", "10%", "250")):
        write("process-" + name, {"type": "process", "name": name + " @Snapmaker U1 (0.4 nozzle)", "instantiation": "true", "layer_height": height, "wall_loops": wall,
                                   "sparse_infill_density": infill, "outer_wall_speed": speed, "inner_wall_speed": str(int(speed) + 50), "sparse_infill_speed": str(int(speed) + 80),
                                   "travel_speed": "400", "enable_prime_tower": "1", "prime_tower_width": "30", "wipe_tower_wall_type": "rib",
                                   "compatible_printers": ["Snapmaker U1 (0.4 nozzle)"]})
    write("pla", {"type": "filament", "name": "Generic PLA @U1", "instantiation": "true", "filament_type": ["PLA"], "compatible_printers": ["Snapmaker U1 (0.4 nozzle)"]})
    write("petg", {"type": "filament", "name": "Generic PETG @U1", "instantiation": "true", "filament_type": ["PETG"], "compatible_printers": ["Snapmaker U1 (0.4 nozzle)"]})
    return program


def main(argv):
    if "--make-engine" in argv:
        print(make_engine(argv[argv.index("--make-engine") + 1]))
        return 0
    record = os.environ.get("STAND_IN_ARGS")
    if record and "--help" not in argv and "--help-fff" not in argv:
        with open(record, "w") as fh:
            json.dump(argv, fh)
    if "--help" in argv:
        print(f"{APP}-{VERSION}:")
        print("Usage: snapmaker-orca [ OPTIONS ] [ file.3mf/file.stl ... ]")
        print("  --export-settings <file>   --slice <plate>   --load-settings <a;b>   --load-filaments <a;b>   --outputdir <folder>")
        return 0
    if "--help-fff" in argv:
        print("  --arrange <0|1>   --orient <0|1>   --allow-newer-file")
        return 0
    if "--export-settings" in argv:
        with open(argv[argv.index("--export-settings") + 1], "w") as fh:
            json.dump({"version": VERSION, "name": "project_settings", "from": "project", "layer_height": "0.2", "nozzle_diameter": ["0.4"]}, fh)
        return 0
    if "--outputdir" in argv:
        out = argv[argv.index("--outputdir") + 1]
        os.makedirs(out, exist_ok=True)
        time.sleep(float(os.environ.get("STAND_IN_DELAY", "0") or 0))

        def result(code, text):
            with open(os.path.join(out, "result.json"), "w") as fh:
                json.dump({"plate_index": 0, "return_code": code, "error_string": text}, fh)
        if os.environ.get("STAND_IN_FAIL"):
            sys.stderr.write("The input model file to the slicer can not be parsed.\n")
            result(-100, "The input model file to the slicer can not be parsed.")
            return 1
        heads = 1 if os.environ.get("STAND_IN_HEADS") == "1" else 2
        with open(os.path.join(out, "plate_1.gcode"), "w") as fh:
            fh.write(gcode(heads))
        result(0, "Success.")
        return 0
    print("stand-in engine: nothing to do", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
