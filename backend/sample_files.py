CENTER = 135.0
LAYER = 0.2
WIDTH = 0.45
E_PER_MM = (WIDTH * LAYER) / (math.pi * (1.75 / 2) ** 2)


def _square_thumbnail(color, size=48):
    """A flat top-view thumbnail: a coloured square on transparent."""
    r, g, b = color
    px = bytearray()
    for y in range(size):
        for x in range(size):
            inside = 8 <= x < size - 8 and 8 <= y < size - 8
            edge = inside and (x in (8, size - 9) or y in (8, size - 9))
            if inside:
                shade = 0.75 if edge else 1.0
                px += bytes((int(r * shade), int(g * shade), int(b * shade), 255))
            else:
                px += b"\x00\x00\x00\x00"
    return mesh_tools.encode_png(size, size, bytes(px))


class _Writer:
    """Accumulates moves and keeps count of time and filament as it goes."""

    def __init__(self):
        self.lines = []
        self.x, self.y, self.z = CENTER, CENTER, 0.0
        self.seconds = 0.0
        self.e_total = {}
        self.tool = 0

    def cmd(self, text):
        self.lines.append(text)

    def travel(self, x, y, z=None, feed=9000):
        dz = 0 if z is None else z - self.z
        dist = math.sqrt((x - self.x) ** 2 + (y - self.y) ** 2 + dz ** 2)
        self.seconds += dist / (feed / 60)
        zpart = "" if z is None else f" Z{z:.2f}"
        self.cmd(f"G0 X{x:.2f} Y{y:.2f}{zpart} F{feed}")
        self.x, self.y = x, y
        if z is not None:
            self.z = z

    def extrude(self, x, y, feed=3000):
        dist = math.hypot(x - self.x, y - self.y)
        e = dist * E_PER_MM
        self.seconds += dist / (feed / 60)
        self.e_total[self.tool] = self.e_total.get(self.tool, 0.0) + e
        self.cmd(f"G1 X{x:.2f} Y{y:.2f} E{e:.5f} F{feed}")
        self.x, self.y = x, y

    def rect(self, cx, cy, w, d):
        x0, y0, x1, y1 = cx - w / 2, cy - d / 2, cx + w / 2, cy + d / 2
        self.travel(x0, y0)
        for x, y in ((x1, y0), (x1, y1), (x0, y1), (x0, y0)):
            self.extrude(x, y)

    def infill(self, cx, cy, w, d, layer_index, spacing=4.0):
        x0, y0, x1, y1 = cx - w / 2, cy - d / 2, cx + w / 2, cy + d / 2
        if layer_index % 2:
            y = y0 + spacing / 2
            while y < y1:
                self.travel(x0, y)
                self.extrude(x1, y)
                y += spacing
        else:
            x = x0 + spacing / 2
            while x < x1:
                self.travel(x, y0)
                self.extrude(x, y1)
                x += spacing


def _gcode(title, colours, types, body, thumb_color):
    """Wrap moves with a PRINT_START/PRINT_END and Orca-style header comments."""
    w = _Writer()
    body(w)
    grams = sum(v * math.pi * (1.75 / 2) ** 2 * 1.24 / 1000 for v in w.e_total.values())
    secs = int(w.seconds)
    thumb = base64.b64encode(_square_thumbnail(thumb_color)).decode("ascii")
    head = [
        f"; {title}",
        "; generated by Deja Vu1's sample_files.py - a simple test shape, not tuned slicer output",
        "; HEADER_BLOCK_START",
        f"; estimated printing time (normal mode) = {secs // 3600}h {secs % 3600 // 60}m {secs % 60}s",
        f"; total filament used [g] = {grams:.2f}",
        f"; total layer number: {w.layers}",
        "; HEADER_BLOCK_END",
        "; THUMBNAIL_BLOCK_START",
        f"; thumbnail begin 48x48 {len(thumb)}",
    ]
    head += ["; " + thumb[i:i + 78] for i in range(0, len(thumb), 78)]
    head += ["; thumbnail end", "; THUMBNAIL_BLOCK_END",
             "PRINT_START TOOL_TEMP=220 BED_TEMP=60 TOOL=0", "M83", "G90"]
    tail = ["PRINT_END",
            "; CONFIG_BLOCK_START",
            "; printer_model = Snapmaker U1",
            "; nozzle_diameter = 0.4,0.4,0.4,0.4",
            f"; layer_height = {LAYER}",
            f"; filament_type = {';'.join(types)}",
            f"; filament_colour = {';'.join(colours)}",
            "; sparse_infill_density = 20%",
            "; wall_loops = 2",
            "; nozzle_temperature = 220,220,220,220",
            "; hot_plate_temp = 60",
            "; CONFIG_BLOCK_END"]
    return "\n".join(head + w.lines + tail) + "\n"


def calibration_cube():
    def body(w):
        layers = 50
        w.layers = layers
        for i in range(layers):
            w.travel(CENTER - 10, CENTER - 10, round(LAYER * (i + 1), 2))
            w.rect(CENTER, CENTER, 20, 20)
            w.rect(CENTER, CENTER, 20 - 2 * WIDTH, 20 - 2 * WIDTH)
            w.infill(CENTER, CENTER, 18, 18, i)
    return _gcode("20 mm calibration cube", ["#F26A1B"], ["PLA"], body, (242, 106, 27))


def three_cubes():
    """
    Three 20 mm cubes side by side, each labelled the way Orca labels
    objects for Klipper (EXCLUDE_OBJECT_DEFINE up front, START/END around
    each object on every layer), so one can be skipped mid-print from the
    Control tab while the other two carry on.
    """
    xs = [CENTER - 35, CENTER, CENTER + 35]
    names = [f"cube.stl_id_{i}_copy_0" for i in range(3)]

    def body(w):
        layers = 50
        w.layers = layers
        for x, name in zip(xs, names):
            corners = [[x - 10, CENTER - 10], [x + 10, CENTER - 10], [x + 10, CENTER + 10], [x - 10, CENTER + 10]]
            polygon = "[" + ",".join(f"[{cx:.3f},{cy:.3f}]" for cx, cy in corners) + "]"
            w.cmd(f"EXCLUDE_OBJECT_DEFINE NAME={name} CENTER={x:.3f},{CENTER:.3f} POLYGON={polygon}")
        for i in range(layers):
            z = round(LAYER * (i + 1), 2)
            for x, name in zip(xs, names):
                w.cmd(f"EXCLUDE_OBJECT_START NAME={name}")
                w.travel(x - 10, CENTER - 10, z)
                w.rect(x, CENTER, 20, 20)
                w.rect(x, CENTER, 20 - 2 * WIDTH, 20 - 2 * WIDTH)
                w.infill(x, CENTER, 18, 18, i)
                w.cmd(f"EXCLUDE_OBJECT_END NAME={name}")
    return _gcode("Three 20 mm calibration cubes, labelled so one can be skipped", ["#F26A1B"], ["PLA"],
                  body, (242, 106, 27))


def two_colour_coaster():
    def body(w):
        layers = 15
        w.layers = layers
        for i in range(layers):
            if i == 10:
                w.cmd("T1")
                w.tool = 1
            w.travel(CENTER - 30, CENTER - 30, round(LAYER * (i + 1), 2))
            w.rect(CENTER, CENTER, 60, 60)
            w.infill(CENTER, CENTER, 58, 58, i, spacing=1.2 if i in (0, 9, 14) else 4.0)
    return _gcode("Two-colour coaster (T0 base, T1 top)", ["#F26A1B", "#1C1C1E"],
                  ["PLA", "PLA"], body, (40, 40, 44))


def unsafe_example():
    """A cube plus a purge line that runs past the U1's 270 mm bed edge."""
    def body(w):
        layers = 20
        w.layers = layers
        w.travel(250, 20, 0.3)
        w.extrude(290, 20)          # 20 mm beyond the bed - pre-flight must catch it
        for i in range(layers):
            w.travel(CENTER - 10, CENTER - 10, round(LAYER * (i + 1), 2))
            w.rect(CENTER, CENTER, 20, 20)
    return _gcode("Unsafe example: purge line past the bed edge", ["#C8102E"], ["PLA"],
                  body, (200, 16, 46))


def dock_bracket_triangles():
    """An L-shaped bracket: the L profile extruded 40 mm, as closed triangles."""
    profile = [(0, 0), (30, 0), (30, 5), (5, 5), (5, 25), (0, 25)]
    depth = 40.0
    tris = []
    n = len(profile)
    # Caps: fan from the inner corner (5,5), which sees every edge of the L.
    hub = 3
    for k in range(n):
        a, b = profile[k], profile[(k + 1) % n]
        if hub in (k, (k + 1) % n):
            continue
        h = profile[hub]
        tris.append(((h[0], 0, h[1]), (b[0], 0, b[1]), (a[0], 0, a[1])))
        tris.append(((h[0], depth, h[1]), (a[0], depth, a[1]), (b[0], depth, b[1])))
    for k in range(n):
        a, b = profile[k], profile[(k + 1) % n]
        p1, p2 = (a[0], 0, a[1]), (b[0], 0, b[1])
        p3, p4 = (b[0], depth, b[1]), (a[0], depth, a[1])
        tris.append((p1, p2, p3))
        tris.append((p1, p3, p4))
    return tris


def dock_bracket_stl():
    return mesh_tools.to_binary_stl(dock_bracket_triangles(), "Deja Vu1 sample dock bracket")


