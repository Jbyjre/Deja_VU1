def _model_xml(triangles, application):
    verts, index, faces = [], {}, []
    for t in triangles:
        ids = []
        for p in t:
            key = tuple(round(c, 4) for c in p)
            if key not in index:
                index[key] = len(verts)
                verts.append(key)
            ids.append(index[key])
        faces.append(ids)
    v = "".join(f'<vertex x="{x}" y="{y}" z="{z}"/>' for x, y, z in verts)
    f = "".join(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in faces)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<model unit="millimeter" xml:lang="en-US" '
            'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">\n'
            f' <metadata name="Application">{application}</metadata>\n'
            f' <resources><object id="1" type="model"><mesh><vertices>{v}</vertices>'
            f'<triangles>{f}</triangles></mesh></object></resources>\n'
            ' <build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 115 115 0"/></build>\n'
            '</model>\n')


