GCODE = b"; generated by a slicer at 10:00\nG28\nG1 X10 Y10 ; move\nG1 X20\n"
SAME_MOVES = b"; generated by a slicer at 11:30, a new date\nG28\nG1 X10 Y10 ; another comment\nG1 X20\n"
STL = b"solid cube\nendsolid cube\n"


def job(name, heads=(("T0", "PLA", "Red", "#ff0000"),), hours=1.0, grams=10.0):
    return {"filename": name, "total_hours": hours, "filament_grams": grams, "material": heads[0][1],
            "required_filament": [{"toolhead": h, "expected_material": m, "expected_color_name": c, "expected_color_hex": x,
                                   "grams": grams} for h, m, c, x in heads]}


def state(name, heads=(("T0", "PLA", "Red", "#ff0000"),), layer=None):
    return {"current_file": name, "active_toolhead": heads[0][0], "layer": layer or {"current": None, "total": None},
            "toolheads": {h: {"filament_material": m, "filament_color_name": c, "filament_color_hex": x} for h, m, c, x in heads}}


def run(name, how, printer="p1", heads=(("T0", "PLA", "Red", "#ff0000"),), layer=None, end_job=None):
    entry = print_record.started(printer, "Bench", state(name, heads), job(name, heads), demo=False)
    recall.describe_start(entry["id"], name)
    print_record.ended(printer, how, state(name, heads, layer), end_job)
    return entry["id"]


class RecallCase(unittest.TestCase):
    def setUp(self):
        print_record.reset()
        recall.reset()
        self.addCleanup(print_record.reset)
        self.addCleanup(recall.reset)
        self.made = []

    def tearDown(self):
        for name in self.made:
            if file_library.exists(name):
                file_library.delete(name)

    def add(self, name, data, note=None):
        file_library.save(name, data, note=note)
        self.made.append(name)


class TestFingerprints(RecallCase):
    def test_gcode_fingerprint_leaves_out_comments(self):
        self.add("recall_a.gcode", GCODE)
        self.add("recall_b.gcode", SAME_MOVES)
        self.add("recall_c.gcode", GCODE + b"G1 X30\n")
        a, b, c = (recall.fingerprint(n) for n in ("recall_a.gcode", "recall_b.gcode", "recall_c.gcode"))
        self.assertEqual(a, b)                                   # the same moves, a new date in the header
        self.assertNotEqual(a, c)
        self.assertIsNone(recall.fingerprint("not_in_files.gcode"))

    def test_fingerprint_follows_a_changed_file(self):
        self.add("recall_a.gcode", GCODE)
        first = recall.fingerprint("recall_a.gcode")
        time.sleep(0.02)
        file_library.save("recall_a.gcode", GCODE + b"G1 X99\n")
        os.utime(file_library._path("recall_a.gcode"), (time.time() + 5, time.time() + 5))
        self.assertNotEqual(recall.fingerprint("recall_a.gcode"), first)


class TestAbout(RecallCase):
    def test_a_file_printed_before_is_known_with_its_history(self):
        self.add("recall_a.gcode", GCODE)
        self.assertEqual(recall.about("recall_a.gcode")["count"], 0)
        good = run("recall_a.gcode", "finished")
        bad = run("recall_a.gcode", "failed", layer={"current": 112, "total": 300})
        info = recall.about("recall_a.gcode")
        self.assertEqual((info["count"], info["counts"]), (2, {"finished": 1, "failed": 1}))
        self.assertEqual(info["last"]["id"], bad)
        self.assertEqual(info["last"]["layer"], {"current": 112, "total": 300})
        self.assertEqual(info["worked"]["id"], good)
        self.assertEqual(info["last_bad"]["id"], bad)
        self.assertTrue(info["worked"]["in_library"])

    def test_the_same_moves_under_another_name_are_recognised(self):
        self.add("recall_a.gcode", GCODE)
        run("recall_a.gcode", "finished")
        self.add("recall_renamed.gcode", SAME_MOVES)                # sliced again with the same settings, saved as a new name
        self.assertEqual(recall.about("recall_renamed.gcode")["count"], 1)

    def test_a_model_knows_the_prints_sliced_from_it(self):
        self.add("recall_part.stl", STL)
        self.add("recall_part.gcode", GCODE, note='Sliced from recall_part.stl with "0.20mm Standard"')
        entry = run("recall_part.gcode", "finished")
        stored = print_record.get(entry)
        self.assertEqual(stored["sliced_from"], "recall_part.stl")
        self.assertEqual(stored["model_fingerprint"], recall.fingerprint("recall_part.stl"))
        info = recall.about("recall_part.stl")
        self.assertEqual(info["count"], 1)
        self.assertEqual(info["last"]["file"], "recall_part.gcode")

    def test_names_match_without_case_or_a_printer_folder(self):
        self.add("recall_a.gcode", GCODE)
        print_record.started("p1", "Bench", state("jobs/Recall_A.gcode"), job("jobs/Recall_A.gcode"), demo=False)
        print_record.ended("p1", "finished", state("jobs/Recall_A.gcode"))
        self.assertEqual(recall.about("recall_a.gcode")["count"], 1)

    def test_a_running_print_is_not_history_yet_and_demo_stays_apart(self):
        self.add("recall_a.gcode", GCODE)
        print_record.started("p1", "Bench", state("recall_a.gcode"), job("recall_a.gcode"), demo=False)
        self.assertEqual(recall.about("recall_a.gcode")["count"], 0)
        self.assertEqual(recall.about("recall_a.gcode", demo=True)["count"], 0)

    def test_a_name_that_is_no_file_is_refused(self):
        with self.assertRaises(ValueError):
            recall.about("notes.txt")


class TestLikeLastTime(RecallCase):
    def test_differences_name_the_head_and_what_changed(self):
        then = [{"toolhead": "T0", "material": "PLA", "colour_name": "Red", "colour": "#ff0000", "spool": "Brand PLA Red"},
                {"toolhead": "T1", "material": "PETG", "colour_name": "Black", "colour": "#000000"}]
        now = [{"toolhead": "T0", "material": "PLA", "colour_name": "Red", "colour": "#ff0000", "spool": "Brand PLA Red"},
               {"toolhead": "T1", "material": "PLA", "colour_name": "White", "colour": "#ffffff"}]
        out = recall.differences(then, now)
        self.assertEqual(len(out), 1)
        self.assertEqual(out[0]["toolhead"], "T1")
        self.assertEqual(out[0]["changed"], ["material", "colour"])
        self.assertEqual(out[0]["then"]["material"], "PETG")
        self.assertEqual(out[0]["now"]["colour_name"], "White")
        self.assertEqual(recall.differences(then, then), [])
        self.assertEqual(recall.differences(then[:1], []), [])       # nothing reported now: no difference is claimed
        unknown = [{"toolhead": "T1", "colour_name": "Black", "colour": "#000000"}]   # the printer does not say the material
        self.assertEqual(recall.differences(then[1:], unknown), [])

    def test_no_finished_print_means_nothing_to_repeat(self):
        self.add("recall_a.gcode", GCODE)
        run("recall_a.gcode", "failed")
        with self.assertRaises(ValueError):
            recall.like_last_time("recall_a.gcode")

    def test_repeat_points_at_the_gcode_that_finished(self):
        self.add("recall_part.stl", STL)
        self.add("recall_part.gcode", GCODE, note='Sliced from recall_part.stl with "0.20mm Standard"')
        run("recall_part.gcode", "finished")
        r = recall.like_last_time("recall_part.stl")
        self.assertEqual(r["file"], "recall_part.gcode")
        self.assertTrue(r["ready"])
        self.assertIsInstance(r["differences"], list)


class TestFacts(RecallCase):
    def test_a_fact_needs_three_prints_with_real_figures(self):
        for _ in range(2):
            run("recall_a.gcode", "finished", end_job={"print_duration_hours": 1.1})
        self.assertEqual([f["kind"] for f in recall.facts()["facts"] if f["kind"] == "time"], [])
        ids = [run("recall_a.gcode", "finished", end_job={"print_duration_hours": 1.1})]
        time_fact = next(f for f in recall.facts()["facts"] if f["kind"] == "time")
        self.assertEqual((time_fact["percent"], time_fact["count"]), (10, 3))
        self.assertIn(ids[0], time_fact["prints"])

    def test_material_and_first_layer_facts_count_endings(self):
        for _ in range(3):
            run("recall_a.gcode", "failed", layer={"current": 2, "total": 100})
        run("recall_a.gcode", "finished")
        facts = {f["kind"]: f for f in recall.facts()["facts"]}
        self.assertEqual((facts["material"]["finished"], facts["material"]["count"]), (1, 4))
        self.assertEqual((facts["first_layers"]["early"], facts["first_layers"]["count"]), (3, 3))

    def test_estimated_grams_never_make_a_filament_fact(self):
        for _ in range(3):
            run("recall_a.gcode", "finished", end_job={"filament_used_grams": 11.0, "filament_grams_estimated": True})
        self.assertNotIn("filament", [f["kind"] for f in recall.facts()["facts"]])
        for _ in range(3):
            run("recall_a.gcode", "finished", end_job={"filament_used_grams": 11.0})
        fact = next(f for f in recall.facts()["facts"] if f["kind"] == "filament")
        self.assertEqual((fact["percent"], fact["count"]), (10, 3))


class TestWatchNotes(RecallCase):
    def test_a_worry_is_kept_on_the_running_print(self):
        entry = print_record.started("p1", "Bench", state("recall_a.gcode"), job("recall_a.gcode"), demo=False)
        print_record.add_watch_note("p1", "Stringing between the towers", "worry", {"current": 40, "total": 200})
        for n in range(print_record.WATCH_NOTES_KEPT + 2):
            print_record.add_watch_note("p1", "note %d" % n, "worry")
        notes = print_record.get(entry["id"])["watch"]
        self.assertEqual(len(notes), print_record.WATCH_NOTES_KEPT)
        self.assertEqual(notes[-1]["why"], "note %d" % (print_record.WATCH_NOTES_KEPT + 1))
        print_record.add_watch_note("p2", "no print here", "worry")    # no running print: nothing is written

    def test_the_first_layer_check_reads_the_layer_the_printer_reports(self):
        ai_assistant_part1._watch["first"].pop("p1", None)
        self.addCleanup(ai_assistant_part1._watch["first"].pop, "p1", None)
        w = {"first_layer": True, "minutes": 10 ** 6}
        now = time.time()
        ai_assistant_part1._watch["last"]["p1"] = now
        self.addCleanup(ai_assistant_part1._watch["last"].pop, "p1", None)
        self.assertIsNone(ai_assistant_part1._watch_due("p1", {"layer": {"current": 1, "total": 90}, "progress": 0.0}, w, now))
        self.assertEqual(ai_assistant_part1._watch_due("p1", {"layer": {"current": 2, "total": 90}, "progress": 0.01}, w, now),
                         "first layers")
        ai_assistant_part1._watch["first"].pop("p1", None)
        self.assertIsNone(ai_assistant_part1._watch_due("p1", {"layer": {"current": 50, "total": 90}, "progress": 0.5}, w, now))


class TestLiveFeedFillsTheFingerprint(RecallCase):
    def test_a_started_print_gets_its_file_fingerprint_in_the_background(self):
        self.add("recall_a.gcode", GCODE)
        pid = mock_moonraker.selected_printer_id()
        with mock_moonraker.use_printer(pid):
            entry_id = live_feed._record_print(pid, "started", state("recall_a.gcode"), None, {}, True)
        self.assertTrue(entry_id)
        for _ in range(100):
            if print_record.get(entry_id, demo=True).get("fingerprint"):
                break
            time.sleep(0.02)
        self.assertEqual(print_record.get(entry_id, demo=True)["fingerprint"], recall.fingerprint("recall_a.gcode"))


class TestRoutes(APITestCase):
    def setUp(self):
        super().setUp()
        print_record.reset()
        self.addCleanup(print_record.reset)

    def test_recall_repeat_and_facts(self):
        file_library.save("recall_route.gcode", GCODE)
        self.addCleanup(file_library.delete, "recall_route.gcode")
        status, body = self.get("/api/prints/recall?file=recall_route.gcode")
        self.assertEqual((status, body["count"]), (200, 0))
        self.assertEqual(self.get("/api/prints/repeat?file=recall_route.gcode")[0], 400)
        run("recall_route.gcode", "finished")
        status, body = self.get("/api/prints/recall?file=recall_route.gcode")
        self.assertEqual((status, body["count"], body["worked"]["file"]), (200, 1, "recall_route.gcode"))
        status, body = self.get("/api/prints/repeat?file=recall_route.gcode")
        self.assertEqual((status, body["file"], body["ready"]), (200, "recall_route.gcode", True))
        self.assertEqual(self.get("/api/prints/recall?file=notes.txt")[0], 400)
        status, body = self.get("/api/prints/facts")
        self.assertEqual((status, body["needs"]), (200, recall.MIN_PRINTS_FOR_A_FACT))

    def test_the_demo_recognises_a_sample_from_the_simulated_history(self):
        status, body = self.get("/api/prints/recall?file=3dbenchy_pla.gcode&demo=1")
        self.assertEqual(status, 200)
        self.assertGreaterEqual(body["count"], 0)                   # the simulated history is random; the shape holds
        self.assertIn("counts", body)


