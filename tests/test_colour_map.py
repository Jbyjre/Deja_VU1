TRI = '<vertex x="0" y="0" z="0"/><vertex x="10" y="0" z="0"/><vertex x="0" y="10" z="0"/>'


def _model(paint, app="BambuStudio-02.03.00.70", attr="paint_color"):
    tris = "".join(f'<triangle v1="0" v2="1" v3="2"{f" {attr}={chr(34)}{p}{chr(34)}" if p else ""}/>' for p in paint)
    return (f'<?xml version="1.0" encoding="UTF-8"?><model unit="millimeter" '
            f'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">'
            f'<metadata name="Application">{app}</metadata><resources><object id="1" type="model"><mesh>'
            f'<vertices>{TRI}</vertices><triangles>{tris}</triangles></mesh></object></resources>'
            f'<build><item objectid="1"/></build></model>')


def five_colour_project(extra_unused=True):
    """A painted Benchy-like part: object on filament 1, paint in 2..5, filament 6 unused (an AMS slot)."""
    colours = ["#F2F2F2", "#E02020", "#1030C0", "#0A1A60", "#20A040", "#FFD000"]
    if not extra_unused:
        colours = colours[:5]
    n = len(colours)
    config = {"printer_model": "Bambu Lab X1 Carbon", "printer_settings_id": "Bambu Lab X1 Carbon 0.4 nozzle",
              "print_settings_id": "0.20mm Standard @BBL X1C", "layer_height": "0.2", "nozzle_diameter": ["0.4"],
              "filament_colour": colours, "filament_type": ["PLA"] * n,
              "filament_settings_id": [f"Bambu PLA Basic {i}" for i in range(n)],
              "nozzle_temperature": [str(200 + i) for i in range(n)],
              "inherits_group": ["0.20mm Standard @BBL X1C"] + [f"Bambu PLA Basic {i}" for i in range(n)] + ["X1C"],
              "different_settings_to_system": ["wall_loops"] + [""] * n + [""],
              "flush_volumes_matrix": [str(0 if i == j else 100 + 10 * i + j) for i in range(n) for j in range(n)],
              "flush_volumes_vector": ["140"] * (2 * n), "support_filament": "0", "wipe_tower_filament": "4",
              "printable_area": ["0x0", "256x0", "256x256", "0x256"]}
    settings = ('<?xml version="1.0" encoding="UTF-8"?><config><object id="1"><metadata key="name" value="Boat"/>'
                '<metadata key="extruder" value="1"/><part id="1" subtype="normal_part">'
                '<metadata key="extruder" value="1"/></part></object>'
                '<plate><metadata key="plater_id" value="1"/>'
                f'<metadata key="filament_maps" value="{" ".join(["1"] * n)}"/></plate></config>')
    # States 2..5 painted: "8" = 2, "0C" = 3, "1C" = 4, "2C" = 5, and one split triangle (4 children 1,2,0,3).
    paint = ["8", "0C", "1C", "2C", "", "0C084" + "3"]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("3D/3dmodel.model", _model(paint))
        z.writestr("Metadata/project_settings.config", json.dumps(config))
        z.writestr("Metadata/model_settings.config", settings)
        z.writestr("Metadata/plate_1.gcode", "; sliced for X1C")
    return buf.getvalue()


def prusa_project():
    model_cfg = ('<?xml version="1.0" encoding="UTF-8"?><config><object id="1" instances_count="1">'
                 '<metadata type="object" key="name" value="Frog"/><metadata type="object" key="extruder" value="5"/>'
                 '<volume firstid="0" lastid="1"><metadata type="volume" key="extruder" value="0"/></volume>'
                 '</object></config>')
    ini = ("; generated by PrusaSlicer 2.8.1\n"
           "; extruder_colour = #00AA00;#FFFFFF;#000000;#FF0000;#00BB00\n"
           "; filament_colour = #00AA00;#FFFFFF;#000000;#FF0000;#00BB00\n"
           "; filament_type = PLA;PLA;PLA;PLA;PLA\n")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("3D/3dmodel.model", _model(["8", "0C", "1C", ""], app="PrusaSlicer-2.8.1",
                                              attr="slic3rpe:mmu_segmentation"))
        z.writestr("Metadata/Slic3r_PE.config", ini)
        z.writestr("Metadata/Slic3r_PE_model.config", model_cfg)
    return buf.getvalue()


def _paints(data, attr="paint_color"):
    model = zipfile.ZipFile(io.BytesIO(data)).read("3D/3dmodel.model").decode()
    return re.findall(r'<triangle[^>]*?(?: ' + re.escape(attr) + r'="([0-9A-F]*)")?/>', model)


class TestPaintCodec(unittest.TestCase):
    def test_states_read_as_orca_writes_them(self):
        self.assertEqual(colour_map.paint_states("4"), {1})
        self.assertEqual(colour_map.paint_states("8"), {2})
        self.assertEqual(colour_map.paint_states("0C"), {3})
        self.assertEqual(colour_map.paint_states("1C"), {4})
        # Orca's own three-colour split example (Model.cpp): children 4, 3, 5, 3, 4.
        self.assertEqual(colour_map.paint_states("1C0C2C0C1C13"), {3, 4, 5})
        # State 18 and above: an F digit then state - 18.
        self.assertEqual(colour_map.paint_states("2FC"), {20})

    def test_unreadable_strings_are_reported_and_left_alone(self):
        self.assertIsNone(colour_map.paint_states("3"))
        self.assertIsNone(colour_map.paint_states("xyz"))
        self.assertEqual(colour_map.remap_paint("3", lambda s: 0), "3")

    def test_remap_keeps_splits_and_changes_only_states(self):
        self.assertEqual(colour_map.remap_paint("1C", lambda s: {4: 2}.get(s, s)), "8")
        self.assertEqual(colour_map.remap_paint("8", lambda s: {2: 5}.get(s, s)), "2C")
        split = colour_map.remap_paint("1C0C2C0C1C13", lambda s: s - 2)
        self.assertEqual(colour_map.paint_states(split), {1, 2, 3})
        self.assertEqual(colour_map.remap_paint("1C0C2C0C1C13", lambda s: s), "1C0C2C0C1C13")

    def test_paint_that_becomes_the_parts_own_colour_disappears(self):
        self.assertEqual(colour_map.remap_paint("8", lambda s: 0), "")


class TestColours(unittest.TestCase):
    def test_names(self):
        for hex_, name in (("#FF0000", "red"), ("#0000FF", "blue"), ("#000080", "dark blue"), ("#FFFFFF", "white"),
                           ("#000000", "black"), ("#808080", "grey"), ("#FFA500", "orange"), ("#8B4513", "brown"),
                           ("#FFC0CB", "pink"), ("#00FF00", "green"), ("#FFFF00", "yellow")):
            self.assertEqual(colour_map.colour_name(hex_), name, hex_)

    def test_distance_follows_how_alike_colours_look(self):
        self.assertLess(colour_map.distance("#1030C0", "#0A1A60"), colour_map.distance("#1030C0", "#E02020"))
        self.assertAlmostEqual(colour_map.distance("#123456", "#123456"), 0.0)


class TestReadAndSuggest(unittest.TestCase):
    def test_reads_what_the_model_uses(self):
        info = colour_map.read(five_colour_project())
        self.assertEqual(info["format"], "orca")
        self.assertEqual(info["source_label"], "MakerWorld / Bambu Studio")
        used = [f["n"] for f in info["filaments"] if f["used"]]
        self.assertEqual(used, [1, 2, 3, 4, 5])  # 4 via the wipe tower and paint; 6 is an empty AMS slot
        self.assertFalse(info["filaments"][5]["used"])
        self.assertEqual(info["filaments"][1]["name"], "red")

    def test_five_colours_fit_four_heads_by_likeness(self):
        info = colour_map.read(five_colour_project())
        plan = colour_map.suggest(info["filaments"])
        self.assertEqual(len({h for h in plan if h is not None}), 4)
        # Blue and navy are the closest pair, so they share a head.
        self.assertEqual(plan[2], plan[3])
        self.assertIsNone(plan[5])

    def test_matching_the_loaded_heads(self):
        info = colour_map.read(five_colour_project())
        loaded = [{"colour": "#FFFFFF"}, {"colour": "#FF0000"}, {"colour": "#0000FF"}, {"colour": "#00FF00"}]
        plan = colour_map.suggest(info["filaments"], loaded)
        self.assertEqual(plan[:5], [0, 1, 2, 2, 3])

    def test_different_materials_are_not_merged_while_another_grouping_exists(self):
        fil = [{"n": i + 1, "colour": c, "type": t, "used": True} for i, (c, t) in enumerate(
            [("#FF0000", "PLA"), ("#FE0000", "TPU"), ("#00FF00", "PLA"), ("#0000FF", "PLA"), ("#0000FE", "PLA")])]
        plan = colour_map.suggest(fil)
        self.assertNotEqual(plan[0], plan[1])
        self.assertEqual(plan[3], plan[4])

    def test_a_used_filament_needs_a_head(self):
        info = colour_map.read(five_colour_project())
        with self.assertRaises(colour_map.ColourMapError):
            colour_map.check_plan(info["filaments"], [0, None, 1, 2, 3, None])
        with self.assertRaises(colour_map.ColourMapError):
            colour_map.check_plan(info["filaments"], [0, 1, 2, 3, 4, None])


class TestApply(unittest.TestCase):
    def test_orca_family_project_is_rewritten_for_four_heads(self):
        out, report = colour_map.apply(five_colour_project())
        cfg = json.loads(zipfile.ZipFile(io.BytesIO(out)).read("Metadata/project_settings.config"))
        self.assertEqual(report["count_after"], 4)
        self.assertEqual(report["dropped"], [6])
        self.assertEqual(len(cfg["filament_colour"]), 4)
        self.assertEqual(len(cfg["filament_type"]), 4)
        self.assertEqual(len(cfg["nozzle_temperature"]), 4)
        self.assertEqual(len(cfg["inherits_group"]), 6)
        self.assertEqual(len(cfg["different_settings_to_system"]), 6)
        self.assertEqual(len(cfg["flush_volumes_matrix"]), 16)
        self.assertEqual(len(cfg["flush_volumes_vector"]), 8)
        self.assertEqual(cfg["filament_colour"][0], "#F2F2F2")
        # The wipe tower used filament 4 (navy), which now shares blue's head.
        self.assertEqual(cfg["wipe_tower_filament"], str(report["plan"][3] + 1))
        self.assertEqual(cfg["support_filament"], "0")
        # Every painted state is now a head 1..4.
        states = set()
        for p in _paints(out):
            if p:
                states |= colour_map.paint_states(p)
        self.assertTrue(states <= {0, 1, 2, 3, 4})
        self.assertIn(report["plan"][4] + 1, states)
        settings = zipfile.ZipFile(io.BytesIO(out)).read("Metadata/model_settings.config").decode()
        self.assertIn('key="filament_maps" value="1 1 1 1"', settings)
        self.assertNotIn("Metadata/plate_1.gcode", zipfile.ZipFile(io.BytesIO(out)).namelist())

    def test_a_chosen_plan_is_followed(self):
        out, report = colour_map.apply(five_colour_project(), [3, 2, 1, 1, 0, None])
        self.assertEqual([h["from"] for h in report["heads"]], [[5], [3, 4], [2], [1]])
        settings = zipfile.ZipFile(io.BytesIO(out)).read("Metadata/model_settings.config").decode()
        self.assertIn('key="extruder" value="4"', settings)
        self.assertNotIn('key="extruder" value="1"', settings)
        self.assertTrue(any("one colour" in w for w in report["warnings"]))

    def test_prusa_project_keeps_its_layout(self):
        info = colour_map.read(prusa_project())
        self.assertEqual(info["format"], "prusa")
        self.assertEqual(info["source_label"], "Printables / PrusaSlicer")
        self.assertEqual([f["n"] for f in info["filaments"] if f["used"]], [2, 3, 4, 5])
        out, report = colour_map.apply(prusa_project())
        cfg = zipfile.ZipFile(io.BytesIO(out)).read("Metadata/Slic3r_PE_model.config").decode()
        self.assertIn('key="extruder" value="4"', cfg)
        self.assertIn('key="extruder" value="0"', cfg)  # a volume's "use the object's" stays
        self.assertEqual(report["count_after"], 4)
        states = set()
        for p in _paints(out, "slic3rpe:mmu_segmentation"):
            if p:
                states |= colour_map.paint_states(p)
        self.assertEqual(states, {1, 2, 3})


class TestConverterUsesTheMap(unittest.TestCase):
    def test_five_colour_makerworld_project_converts(self):
        out, report = converter_3mf.convert(five_colour_project())
        cfg = json.loads(zipfile.ZipFile(io.BytesIO(out)).read("Metadata/project_settings.config"))
        self.assertEqual(len(cfg["filament_colour"]), 4)
        self.assertEqual(len(cfg["filament_settings_id"]), 4)
        self.assertEqual(len(cfg["inherits_group"]), 6)
        self.assertEqual(report["colours"]["count_after"], 4)
        self.assertFalse(any("toolheads" in w and "Reassign" in w for w in report["warnings"]))

    def test_other_orca_family_slicers_are_recognised(self):
        for app, label in (("CrealityPrint-6.1.0", "Creality Print"), ("AnycubicSlicerNext-1.3.7", "Anycubic"),
                           ("QIDIStudio-2.0", "QIDI Studio"), ("SomeFork-1.0", "OrcaSlicer-family")):
            data = five_colour_project()
            buf = io.BytesIO()
            with zipfile.ZipFile(io.BytesIO(data)) as src, zipfile.ZipFile(buf, "w") as dst:
                for item in src.infolist():
                    body = src.read(item.filename)
                    if item.filename == "3D/3dmodel.model":
                        body = body.replace(b"BambuStudio-02.03.00.70", app.encode())
                    dst.writestr(item, body)
            cfg = json.loads(zipfile.ZipFile(io.BytesIO(buf.getvalue())).read("Metadata/project_settings.config"))
            cfg["printer_model"] = "Some printer"
            out, report = converter_3mf.convert(_with_config(buf.getvalue(), cfg))
            self.assertIn(label, report["source_label"])

    def test_prusa_project_converts(self):
        out, report = converter_3mf.convert(prusa_project())
        self.assertEqual(report["source"], "prusa")
        self.assertEqual(report["colours"]["count_after"], 4)
        self.assertIn("Metadata/Slic3r_PE_model.config", zipfile.ZipFile(io.BytesIO(out)).namelist())


def _with_config(data, cfg):
    buf = io.BytesIO()
    with zipfile.ZipFile(io.BytesIO(data)) as src, zipfile.ZipFile(buf, "w") as dst:
        for item in src.infolist():
            body = json.dumps(cfg).encode() if item.filename == "Metadata/project_settings.config" \
                else src.read(item.filename)
            dst.writestr(item, body)
    return buf.getvalue()


